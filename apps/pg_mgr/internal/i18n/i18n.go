var currentLang = "en"

func init() {
	InitLang()
}

func InitLang() {
	langEnv := os.Getenv("LANG")
	if strings.Contains(langEnv, "zh_CN") || strings.Contains(langEnv, "zh_SG") {
		currentLang = "zh-CN"
	}
}

func T(key string, args ...interface{}) string {
	msg, ok := translationMap[currentLang][key]
	if !ok {
		msg, ok = translationMap["en"][key]
		if !ok {
			return key
		}
	}
	return fmt.Sprintf(msg, args...)
}
